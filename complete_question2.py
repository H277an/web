                "    \n",
                "    # Layer 3: Secondary Visual Cortex (V2) - Shapes and Textures\n",
                "    # Combines edges into more complex patterns\n",
                "    x = layers.Conv2D(64, (3, 3), activation='relu', padding='same',\n",
                "                      name='V2_texture_detection')(x)\n",
